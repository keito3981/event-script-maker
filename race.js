const toMin = t => { const m = /^(\d{1,2}):(\d{2})/.exec(t || ''); return m ? (+m[1]) * 60 + (+m[2]) : null; };
const fromMin = n => n == null ? '' : `${Math.floor(n / 60) % 24}:${String(((n % 60) + 60) % 60).padStart(2,'0')}`;
const jp = n => { if (n == null) return ''; const h = Math.floor(n / 60), m = n % 60; return m ? `${h}時${m}分` : `${h}時`; };
const durLabel = m => { m = Number(m) || 0; const h = Math.floor(m / 60), r = m % 60; return h ? `${h}時間${r ? r + '分' : ''}` : `${r}分`; };
const num = v => Math.max(0, Number(v) || 0);

function computed(v){
  const c = {...v};
  c.dateLabel = (() => {
    const d = v.date && new Date(v.date + 'T00:00:00');
    if (!d || isNaN(d)) return '日付未定';
    return `${d.getFullYear()}年${d.getMonth()+1}月${d.getDate()}日（${'日月火水木金土'[d.getDay()]}）`;
  })();
  c.teamList = String(v.teams || '').split(/[、,，]/).map(t => t.trim()).filter(Boolean);
  c.teamUp = fromMin(toMin(v.opening) - 30);
  c.lineUp = fromMin(toMin(v.opening) - 5);
  c.opening_jp = jp(toMin(v.opening));
  return c;
}

